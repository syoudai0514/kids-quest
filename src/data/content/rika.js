function shuffle(arr) {
  const a = [...arr]
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[a[i], a[j]] = [a[j], a[i]]
  }
  return a
}
function pick(arr) {
  return arr[Math.floor(Math.random() * arr.length)]
}

// 直近に出した設問は しばらく除外する（固定文の問題バンクなので、
// 単純な毎回ランダムだと 同じ問題が連続で出てしまうことがあった）
let recentQs = []
const RECENT_MAX = 3
// 一度も出したことのない設問を最優先する（未出優先）。everSeen は
// ActivityPlayer が state.srs['rika'] の既存キーから渡す「既出」集合で、
// 全部見たことがあれば、直近に出した設問を避けるだけの従来ロジックへ戻る。
function pickFresh(pool, everSeen) {
  const unseen = everSeen ? pool.filter((it) => !everSeen.has(`r:${it.q}`)) : []
  const source = unseen.length ? unseen : pool.filter((it) => !new Set(recentQs).has(it.q))
  const chosen = pick(source.length ? source : pool)
  recentQs = [chosen.q, ...recentQs].slice(0, RECENT_MAX)
  return chosen
}

// 小3〜6。前学年の内容はSRS復習で扱う。通常出題に混ぜると、その学年の
// 単元台帳に無い設問が進級記録へ混ざるため、ここは現学年だけにする。
function poolForGrade(grade) {
  const g = Math.max(3, Math.min(6, grade))
  return [...BANK[g]]
}

const ALL = Object.values(BANK).flat()
const BY_Q = Object.fromEntries(ALL.map((x) => [x.q, x]))

function build(item, cc) {
  // 正解だけが長いという見た目の手掛かりを消すため、最長の誤答は必ず含める
  // （doutoku.js と同じ方式）。これが無いと、理科は正解が単独最長になる割合が
  // 43%（偶然なら25%）まで上がり、「いちばん長いものを選ぶ」だけで当たってしまう。
  const longestWrong = [...item.d].sort((a, b) => b.length - a.length)[0]
  const otherWrong = shuffle(item.d.filter((value) => value !== longestWrong)).slice(0, Math.max(1, cc - 2))
  const opts = shuffle([item.a, longestWrong, ...otherWrong])
  return {
    domain: 'rika',
    unitId: item.unitId,
    skillId: item.unitId,
    type: 'choice',
    itemKey: `r:${item.q}`,
    visual: { kind: 'bigtext', text: '🔬' },
    instruction: item.q,
    speak: item.q,
    answerId: item.a,
    choices: opts.map((v) => ({ id: v, label: v, speak: v })),
    answerWord: { text: item.a },
    explain: item.e
  }
}

export function generateRikaQuestion(params, reviewKey = null) {
  const cc = Math.max(3, params.choiceCount || 3)
  if (reviewKey && reviewKey.startsWith('r:')) {
    const it = BY_Q[reviewKey.slice(2)]
    if (it) return build(it, cc)
  }
  if (params.unitId) {
    const pool = ALL.filter((item) => item.unitId === params.unitId)
    if (pool.length) return build(pickFresh(pool, params.everSeenKnowledge), cc)
    return null
  }
  return build(pickFresh(poolForGrade(params.grade || 3), params.everSeenKnowledge), cc)
}

